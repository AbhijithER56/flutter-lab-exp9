"""End-to-end test of the Flutter web build in real Chrome against the REAL
Cloud Firestore `books` collection, plus output screenshots.

Usage (from the project root, after `flutter build web`):
    python tool/e2e_chrome_test.py screenshots

Books are added manually in the Firebase Console. All writes are made by the
app's Update button; this script only reads `books` through the REST API to
check that exactly the `copies` field of the searched document changed.
"""
import json, os, subprocess, sys, time, urllib.request
from playwright.sync_api import sync_playwright, expect

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PORT = 8779
URL = f"http://127.0.0.1:{PORT}/"
ARGS = [a for a in sys.argv[1:] if not a.startswith("--")]
SHOTS = os.path.abspath(ARGS[0] if ARGS else "screenshots")
os.makedirs(SHOTS, exist_ok=True)

# Real project config generated by `flutterfire configure`.
opts = open(os.path.join(ROOT, "lib", "firebase_options.dart"), encoding="utf-8").read()
PROJECT = opts.split("projectId: '")[1].split("'")[0]
API_KEY = opts.split("static const FirebaseOptions web")[1].split("apiKey: '")[1].split("'")[0]
REST = (f"https://firestore.googleapis.com/v1/projects/{PROJECT}"
        f"/databases/(default)/documents/books")

SUCCESS = "Book updated successfully"


def step(msg):
    print(msg, flush=True)


def rest_books():
    """{doc id: {"title", "author", "copies", "updateTime"}} from Firestore."""
    with urllib.request.urlopen(f"{REST}?key={API_KEY}&pageSize=300") as r:
        docs = json.load(r).get("documents", [])
    out = {}
    for d in docs:
        f = d.get("fields", {})
        c = f.get("copies", {})
        copies = c.get("integerValue", c.get("doubleValue", c.get("stringValue")))
        out[d["name"].split("/")[-1]] = {
            "title": f.get("title", {}).get("stringValue"),
            "author": f.get("author", {}).get("stringValue"),
            "copies": None if copies is None else int(float(copies)),
            "updateTime": d["updateTime"],
        }
    return out


def find_id(books, title):
    return next((i for i, b in books.items() if b["title"] == title), None)


def launch(p, viewport=(1280, 860)):
    browser = p.chromium.launch(channel="chrome", headless=True)
    ctx = browser.new_context(viewport={"width": viewport[0], "height": viewport[1]})
    page = ctx.new_page()
    page.on("console", lambda m: m.type == "error" and print("CONSOLE:", m.text))
    return browser, page


def open_app(page):
    page.goto(URL)
    page.wait_for_selector("flt-semantics-placeholder", state="attached", timeout=60000)
    page.locator("flt-semantics-placeholder").dispatch_event("click")
    expect(page.get_by_role("button", name="Search")).to_be_visible(timeout=30000)
    page.wait_for_timeout(800)


def text(page, value):
    # Only the visible semantics tree, not Flutter's screen-reader announcements.
    return page.locator("flt-semantics-host").get_by_text(value, exact=True)


def type_into(page, label, value):
    box = page.get_by_role("textbox", name=label)
    box.click()
    page.wait_for_timeout(250)  # let Flutter move focus before typing
    page.keyboard.press("Control+A")
    page.keyboard.press("Backspace")
    if value:
        page.keyboard.type(value, delay=15)


def search(page, title):
    type_into(page, "Enter Book Title", title)
    page.get_by_role("button", name="Search").click()


def update(page, copies):
    type_into(page, "Enter Updated Copies", copies)
    page.get_by_role("button", name="Update").click()


def expect_card(page, title, author, copies):
    # Flutter web merges the result card into one semantics node.
    card = page.locator("flt-semantics-host").get_by_text(
        f"Title: {title} Author: {author} Copies Available: {copies}")
    expect(card).to_be_visible(timeout=30000)


def shot(page, name):
    page.screenshot(path=os.path.join(SHOTS, name))
    step(f"   screenshot -> screenshots/{name}")


def check_only_copies_changed(before, after, doc_id, copies):
    assert set(after) == set(before), "no document may be added or removed"
    for i, b in before.items():
        a = after[i]
        assert (a["title"], a["author"]) == (b["title"], b["author"]), f"{i} title/author changed"
        if i == doc_id:
            assert a["copies"] == copies, f"{i} copies is {a['copies']}, expected {copies}"
            assert a["updateTime"] != b["updateTime"], f"{i} was not written"
        else:
            assert a == b, f"{i} must not change"
    step(f"   Firestore verified: books/{doc_id} copies = {after[doc_id]['copies']} "
         f"(updateTime {after[doc_id]['updateTime']}), other docs unchanged, "
         f"{len(after)} docs total")


def search_and_update(page, title, new_copies, shot_found, shot_updated):
    before = rest_books()
    doc_id = find_id(before, title)
    if doc_id is None:
        step(f"   SKIPPED: '{title}' is not in Firestore yet")
        return False
    book = before[doc_id]
    step(f"   Firestore before: books/{doc_id} copies = {book['copies']}")
    search(page, title)
    expect_card(page, title, book["author"], book["copies"])
    if shot_found:
        shot(page, shot_found)
    update(page, str(new_copies))
    expect(text(page, SUCCESS)).to_be_visible(timeout=30000)
    expect_card(page, title, book["author"], new_copies)
    shot(page, shot_updated)
    check_only_copies_changed(before, rest_books(), doc_id, new_copies)
    return True


def main():
    start = rest_books()
    step(f"Firestore project {PROJECT}: books has {len(start)} docs:")
    for i, b in start.items():
        step(f"   {i}: {b['title']!r} by {b['author']!r}, copies={b['copies']}")

    server = subprocess.Popen([sys.executable, "-m", "http.server", str(PORT),
                               "--directory", os.path.join(ROOT, "build", "web")],
                              stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    time.sleep(1.5)
    missing = []
    try:
        with sync_playwright() as p:
            browser, page = launch(p)
            open_app(page)
            shot(page, "01_update_screen.png")

            # Test case 2 asks for 0 -> 5, so bring a re-run back to 0 first
            # (through the app's own Update button).
            pid = find_id(start, "Python Programming")
            if pid and start[pid]["copies"] != 0:
                step("SETUP   Python Programming is not 0; resetting to 0 via the app")
                search_and_update(page, "Python Programming", 0, None, "00_reset.png")
                os.remove(os.path.join(SHOTS, "00_reset.png"))

            step("TEST 1-3  Search 'Python Programming', update copies 0 -> 5")
            if not search_and_update(page, "Python Programming", 5,
                                     "02_python_search.png", "03_python_updated.png"):
                missing.append("Python Programming")

            step("TEST 4  Search 'Artificial Intelligence' and update its copies")
            ai = find_id(rest_books(), "Artificial Intelligence")
            ai_new = 7 if ai is None or start[ai]["copies"] != 7 else 4
            if not search_and_update(page, "Artificial Intelligence", ai_new,
                                     "04_ai_search.png", "05_ai_updated.png"):
                missing.append("Artificial Intelligence")

            step("TEST 5  Unknown title shows 'Book not found'")
            search(page, "Data Structures")
            expect(text(page, "Book not found")).to_be_visible(timeout=30000)
            shot(page, "06_book_not_found.png")

            step("TEST 6  Empty inputs show validation messages")
            before = rest_books()
            search(page, "   ")
            expect(text(page, "Please enter a book title to search")).to_be_visible(timeout=10000)
            shot(page, "07_empty_title.png")
            update(page, "5")
            expect(text(page, "Please search for a book before updating")).to_be_visible(timeout=10000)
            search(page, "Flutter Basics")
            expect(page.locator("flt-semantics-host").get_by_text("Title: Flutter Basics")).to_be_visible(timeout=30000)
            update(page, "")
            expect(text(page, "Please enter the updated number of copies")).to_be_visible(timeout=10000)
            shot(page, "08_empty_copies.png")
            update(page, "-3")
            expect(text(page, "Copies must be a whole number (0 or more)")).to_be_visible(timeout=10000)
            shot(page, "09_invalid_copies.png")
            assert rest_books() == before, "rejected input must not write to Firestore"
            step("   Firestore unchanged by invalid input")
            browser.close()

            step("Responsive layout (phone-size window)")
            browser, page = launch(p, viewport=(412, 915))
            open_app(page)
            search(page, "Python Programming")
            page.wait_for_timeout(3000)
            shot(page, "10_mobile_layout.png")
            browser.close()

        step("Final Firestore state:")
        for i, b in rest_books().items():
            step(f"   {i}: {b['title']!r} by {b['author']!r}, copies={b['copies']}")
        if missing:
            step(f"INCOMPLETE: add these books in Firebase Console and re-run: {missing}")
            sys.exit(2)
        step("ALL E2E TESTS PASSED")
    finally:
        server.terminate()


if __name__ == "__main__":
    main()
