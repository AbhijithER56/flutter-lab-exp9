import 'package:flutter/material.dart';
import 'package:firebase_core/firebase_core.dart';

import 'firebase_options.dart';
import 'update_book_screen.dart';

// Palette: cobalt ink with a hot-pink action colour on a cool page
const Color kCobalt = Color(0xFF2740D8);
const Color kViolet = Color(0xFF5B3DF5);
const Color kPink = Color(0xFFFF3D81);
const Color kPage = Color(0xFFF2F4FB);
const Color kInk = Color(0xFF1B2250);
const Color kMuted = Color(0xFF6C7599);

Future<void> main() async {
  // Required before calling native code (Firebase) ahead of runApp().
  WidgetsFlutterBinding.ensureInitialized();

  // Reuses the Experiment 7/8 Firebase project. Options generated by
  // `flutterfire configure` (lib/firebase_options.dart) for Android and Web.
  // Android also uses android/app/google-services.json.
  Object? initError;
  try {
    await Firebase.initializeApp(
      options: DefaultFirebaseOptions.currentPlatform,
    );
  } catch (e) {
    initError = e;
  }

  runApp(LibraryApp(initError: initError));
}

class LibraryApp extends StatelessWidget {
  const LibraryApp({super.key, this.initError});

  /// Non-null when Firebase failed to initialize.
  final Object? initError;

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'Update Book Copies',
      debugShowCheckedModeBanner: false,
      theme: ThemeData(
        colorScheme: ColorScheme.fromSeed(seedColor: kCobalt),
        scaffoldBackgroundColor: kPage,
        appBarTheme: const AppBarTheme(
          backgroundColor: kCobalt,
          foregroundColor: Colors.white,
          centerTitle: true,
          elevation: 0,
        ),
        useMaterial3: true,
      ),
      home: initError == null
          ? const UpdateBookScreen()
          : _FirebaseErrorScreen(error: initError!),
    );
  }
}

/// Shown instead of the update screen when Firebase could not start,
/// so the problem is visible rather than a blank or crashing app.
class _FirebaseErrorScreen extends StatelessWidget {
  const _FirebaseErrorScreen({required this.error});

  final Object error;

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(title: const Text('Update Book Copies')),
      body: Center(
        child: Padding(
          padding: const EdgeInsets.all(24),
          child: Text(
            'Firebase initialization failed.\n\n'
            'Check lib/firebase_options.dart (run `flutterfire configure`) '
            'and android/app/google-services.json.\n\nError: $error',
            textAlign: TextAlign.center,
            style: const TextStyle(color: Colors.red),
          ),
        ),
      ),
    );
  }
}
